/**
 * 应用内语言设置：持久化语言代码；FOLLOW=跟随系统。
 * 语言表为代码级翻译表，中文（简体）为兜底语言。
 */
object LanguageStore {
    const val FOLLOW = "follow"
    private const val PREFS = "settings"
    private const val KEY = "lang"

    fun load(context: Context): String =
        context.getSharedPreferences(PREFS, Context.MODE_PRIVATE).getString(KEY, "zh") ?: "zh"

    fun save(context: Context, code: String) {
        context.getSharedPreferences(PREFS, Context.MODE_PRIVATE).edit().putString(KEY, code).apply()
    }
}

